package app.lock.media.transcode;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

import app.lock.config.LockProperties;
import java.awt.image.BufferedImage;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Duration;
import java.util.List;
import java.util.concurrent.TimeUnit;
import javax.imageio.ImageIO;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/**
 * Runs the real ffmpeg (roadmap 2.8). Skipped when no {@code ffmpeg} is on the PATH; CI installs it.
 * Inputs are generated by ffmpeg itself (test patterns), so no media fixtures are committed.
 */
class FfmpegTranscoderTest {

    @TempDir
    static Path dir;

    static FfmpegTranscoder ffmpeg;

    @BeforeAll
    static void requireFfmpeg() throws Exception {
        assumeTrue(available(), "ffmpeg not installed");
        var props = new LockProperties(false, null, null, null, null, null, null, null, null, null, null, null,
                new LockProperties.Transcode("ffmpeg", "ffmpeg", Duration.ofMinutes(2)), null, null);
        ffmpeg = new FfmpegTranscoder(props);
    }

    @Test
    void videoBecomesAStreamableH264Mp4WithinTheSizeLimit_andMetadataIsDropped() throws Exception {
        Path original = dir.resolve("in.mov");
        generate("-f", "lavfi", "-i", "testsrc=size=1920x1080:rate=30:duration=2",
                "-f", "lavfi", "-i", "sine=frequency=440:duration=2",
                "-metadata", "location=+48.8584+002.2945/", "-c:v", "mpeg4", "-c:a", "pcm_s16le", original.toString());
        Path out = dir.resolve("playback.mp4");

        ffmpeg.videoPlayback(original, out, 1280);

        String probe = probe(out);
        assertThat(probe).contains("codec_name=h264").contains("codec_name=aac").contains("width=1280").contains("height=720");
        assertThat(probe).doesNotContain("48.8584");
        // faststart: the moov atom comes before the media data, so playback starts before the download ends.
        byte[] head = Files.readAllBytes(out);
        assertThat(indexOf(head, "moov")).isLessThan(indexOf(head, "mdat"));
    }

    @Test
    void smallVideosAreNotUpscaled() throws Exception {
        Path original = dir.resolve("small.mp4");
        generate("-f", "lavfi", "-i", "testsrc=size=320x240:rate=10:duration=1", original.toString());
        Path out = dir.resolve("small-playback.mp4");
        ffmpeg.videoPlayback(original, out, 1280);
        assertThat(probe(out)).contains("width=320").contains("height=240");
    }

    @Test
    void audioBecomesAac() throws Exception {
        Path original = dir.resolve("note.wav");
        generate("-f", "lavfi", "-i", "sine=frequency=220:duration=1", original.toString());
        Path out = dir.resolve("note.mp4");
        ffmpeg.audioPlayback(original, out);
        assertThat(probe(out)).contains("codec_name=aac").doesNotContain("codec_type=video");
    }

    @Test
    void stillFrameAndImageDecoding() throws Exception {
        Path video = dir.resolve("clip.mp4");
        generate("-f", "lavfi", "-i", "testsrc=size=640x360:rate=10:duration=0.5", video.toString()); // shorter than 1s
        Path still = dir.resolve("still.png");
        ffmpeg.videoStill(video, still);
        BufferedImage frame = ImageIO.read(still.toFile());
        assertThat(frame.getWidth()).isEqualTo(640);

        // A PNG through decodeImage stands in for HEIC, which ffmpeg builds cannot always encode.
        Path png = dir.resolve("photo-in.png");
        generate("-f", "lavfi", "-i", "testsrc=size=400x300", "-frames:v", "1", png.toString());
        assertThat(ffmpeg.decodeImage(png, dir.resolve("photo.png"))).isPresent();
        assertThat(ImageIO.read(dir.resolve("photo.png").toFile()).getWidth()).isEqualTo(400);
    }

    @Test
    void webpDecodes() throws Exception {
        // Not every ffmpeg build encodes WebP, but they all decode it; make the fixture with cwebp if needed.
        Path png = dir.resolve("for-webp.png");
        generate("-f", "lavfi", "-i", "testsrc=size=400x300", "-frames:v", "1", png.toString());
        Path webp = dir.resolve("photo.webp");
        boolean made = run("ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", png.toString(), webp.toString())
                || run("cwebp", "-quiet", png.toString(), "-o", webp.toString());
        assumeTrue(made, "no WebP encoder available to build the fixture");
        assertThat(ffmpeg.decodeImage(webp, dir.resolve("webp.png"))).isPresent();
        assertThat(ImageIO.read(dir.resolve("webp.png").toFile()).getHeight()).isEqualTo(300);
    }

    private static boolean run(String... cmd) {
        try {
            Process p = new ProcessBuilder(cmd).redirectErrorStream(true).redirectOutput(ProcessBuilder.Redirect.DISCARD).start();
            return p.waitFor(60, TimeUnit.SECONDS) && p.exitValue() == 0;
        } catch (Exception e) {
            return false;
        }
    }

    @Test
    void garbageFailsCleanly() throws Exception {
        Path junk = dir.resolve("junk.mp4");
        Files.writeString(junk, "not a video");
        assertThatThrownBy(() -> ffmpeg.videoPlayback(junk, dir.resolve("junk-out.mp4"), 1280))
                .isInstanceOf(FfmpegTranscoder.TranscodeException.class)
                .hasMessageContaining("ffmpeg exited");
        assertThat(ffmpeg.decodeImage(junk, dir.resolve("junk.png"))).isEmpty();
    }

    private static boolean available() {
        try {
            return new ProcessBuilder("ffmpeg", "-version").redirectErrorStream(true)
                    .redirectOutput(ProcessBuilder.Redirect.DISCARD).start().waitFor(10, TimeUnit.SECONDS);
        } catch (Exception e) {
            return false;
        }
    }

    private static void generate(String... args) throws Exception {
        List<String> cmd = new java.util.ArrayList<>(List.of("ffmpeg", "-hide_banner", "-loglevel", "error", "-y"));
        cmd.addAll(List.of(args));
        Process p = new ProcessBuilder(cmd).inheritIO().start();
        assertThat(p.waitFor(60, TimeUnit.SECONDS) && p.exitValue() == 0).as("generate %s", cmd).isTrue();
    }

    private static String probe(Path file) throws Exception {
        Process p = new ProcessBuilder("ffprobe", "-v", "error", "-show_streams", "-show_format", file.toString())
                .redirectErrorStream(true).start();
        String out = new String(p.getInputStream().readAllBytes());
        p.waitFor(30, TimeUnit.SECONDS);
        return out;
    }

    private static int indexOf(byte[] haystack, String needle) {
        byte[] n = needle.getBytes();
        outer:
        for (int i = 0; i <= haystack.length - n.length; i++) {
            for (int j = 0; j < n.length; j++) {
                if (haystack[i + j] != n[j]) {
                    continue outer;
                }
            }
            return i;
        }
        return Integer.MAX_VALUE;
    }
}
